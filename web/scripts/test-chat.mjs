import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe",headless:"new",args:["--no-sandbox"]});
const page = await browser.newPage();
await page.setViewport({width:1440,height:900});
await page.goto("http://localhost:3100/",{waitUntil:"networkidle0"});
await page.evaluate(()=>localStorage.setItem("amy_age_ok","1"));
await page.goto("http://localhost:3100/chat",{waitUntil:"networkidle0"});
await page.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>x.textContent?.includes('Valeria Soto'));b?.click();});
await new Promise(r=>setTimeout(r,300));
const out={};
out.header = await page.evaluate(()=>document.body.innerText.includes('Camila Rivas') && document.body.innerText.includes('Valeria Soto'));
out.valeriaMessages = await page.evaluate(()=>document.body.innerText.includes('¿Entrenamos mañana? Te preparé'));
out.rightPanel = await page.evaluate(()=>document.body.innerText.includes('@valesoto'));
await page.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>x.getAttribute('aria-label')==='Videollamada');b?.click();});
await new Promise(r=>setTimeout(r,300));
out.callModal = await page.evaluate(()=>document.body.innerText.includes('Llamada en curso') && document.body.innerText.includes('Valeria Soto'));
await page.evaluate(()=>{const b=document.querySelector('button[aria-label="Colgar"]');b?.click();});
await new Promise(r=>setTimeout(r,300));
out.callEnded = await page.evaluate(()=>document.body.innerText.includes('Llamada finalizada') || document.body.innerText.includes('Llamada finalizada ·'));
console.log(JSON.stringify(out,null,2));
await browser.close();
